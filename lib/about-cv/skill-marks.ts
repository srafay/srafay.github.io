/** A skill's glyph: its exact mark where one exists, else its CV group's line glyph. */
export function glyphOfSkill(skill: Pick<SkillWord, "word" | "group">): Glyph {
  const mark = skillMarks[skill.word];
  return mark ? markGlyph(mark) : groupGlyphs[skill.group];
}

export const hasMark = (word: string) => word in skillMarks;

/** Fails on a mapped word that is not a skill or a glyph with no drawing, and says how many skills carry what. */
export function checkSkillMarks(skills: SkillWord[]) {
  const words = new Set(skills.map((skill) => skill.word));
  for (const word of Object.keys(skillMarks))
    if (!words.has(word))
      throw new Error(`skill-marks.ts maps "${word}", which is not a skill`);
  for (const skill of skills)
    checkGlyph(glyphOfSkill(skill), `the skill ${skill.word}`);
  const marked = skills.filter((skill) => hasMark(skill.word)).length;
  return {
    skills: skills.length,
    marks: marked,
    groupGlyphs: skills.length - marked,
    none: 0,
  };
}
